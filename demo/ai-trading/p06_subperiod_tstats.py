START = (1927, 1)  # first month of HML


def month_index(year, month):
    return (year - START[0]) * 12 + (month - START[1])


def window(y0, m0, y1, m1):
    return HML[month_index(y0, m0): month_index(y1, m1) + 1]


def summary(x):
    n = len(x)
    se = x.std(ddof=1) / np.sqrt(n)
    return n, x.mean() * 12, x.mean() / se


# 1. Whole record, then two halves of about fifty years each
periods = {
    "1927-01..2026-09 (all)": window(1927, 1, 2026, 9),
    "1927-01..1976-12 (first half)": window(1927, 1, 1976, 12),
    "1977-01..2026-09 (second half)": window(1977, 1, 2026, 9),
    "2007-01..2026-09 (last 20 years)": window(2007, 1, 2026, 9),
}
print(f"{'period':34s} {'months':>6s} {'%/yr':>6s} {'t':>6s}")
for name, x in periods.items():
    n, ann, t = summary(x)
    print(f"{name:34s} {n:6d} {ann:6.2f} {t:6.2f}")

# 2. Are the two halves different from each other? (Welch t on monthly means)
a, b = periods["1927-01..1976-12 (first half)"], periods["1977-01..2026-09 (second half)"]
diff_t = (a.mean() - b.mean()) / np.sqrt(a.var(ddof=1) / len(a) + b.var(ddof=1) / len(b))
print(f"\nfirst minus second half: {(a.mean() - b.mean()) * 12:.2f} %/yr, Welch t = {diff_t:.2f}")

# 3. How many years would the second-half premium need to reach t = 2?
mu, sd = b.mean(), b.std(ddof=1)
years = (2 * sd / mu) ** 2 / 12
print(f"second half: monthly sd {sd:.2f}%, years of data needed for t = 2: {years:.0f}")
